-- Verify built-in v0.9.8 language defaults and user-controlled dungeon names.
GetLocale=function() return 'enUS' end
ForeverQuickJoinDB={languageChoice='frFR',theme='Forever',themeTransparency=false}
assert(loadfile('ForeverQuickJoin_Locale.lua'))()
local locale=assert(ForeverQuickJoinLocale)
assert(locale.Current()=='frFR')
assert(locale.DungeonNamesEnabled(),'non-English defaults dungeon translation to on')
assert(locale.TranslateDungeonName('City of Dalaran',2)=='Cité de Dalaran')
assert(locale.TranslateDungeonName('Razorfen Kraul',2)=='Kraal de Tranchebauge')
assert(locale.TranslateDungeonName('Scarlet Library',3)=='Scarlet Library',
    'non-dungeon categories must retain original activity names')
assert(locale.TranslateDungeonName('Unknown Forever Dungeon',2)=='Unknown Forever Dungeon')
assert(locale.DefaultWhisperTemplate(false,'english solo'):find('cherche un groupe',1,true))
assert(locale.DefaultWhisperTemplate(true,''):find('{party}',1,true))
locale.SetTranslateDungeonNames(false)
assert(ForeverQuickJoinDB.translateDungeonNames==false)
assert(locale.TranslateDungeonName('Scarlet Library',2)=='Scarlet Library')
locale.Select('deDE')
assert(locale.Current()=='deDE' and not locale.DungeonNamesEnabled(),
    'explicit translation choice must persist across language changes')
locale.SetTranslateDungeonNames(true)
assert(locale.TranslateDungeonName('Razorfen Kraul',2)=='Kral der Klingenhauer')
locale.Select('esES')
assert(locale.TranslateDungeonName('Scarlet Monastery',2)=='Monasterio Escarlata')
locale.Select('ptBR')
assert(locale.TranslateDungeonName('City of Dalaran',2)=='Cidade de Dalaran')
locale.Select('ruRU')
assert(locale.TranslateDungeonName('Gnomeregan',2)=='Гномреган')
locale.Select('zhCN')
assert(locale.TranslateDungeonName('Gnomeregan',2)=='诺莫瑞根')
locale.Select('zhTW')
assert(locale.TranslateDungeonName('Gnomeregan',2)=='諾姆瑞根')
locale.Select('koKR')
assert(locale.TranslateDungeonName('Gnomeregan',2)=='놈리건')
locale.Select('enUS')
assert(locale.TranslateDungeonName('City of Dalaran',2)=='City of Dalaran')
assert(locale.DefaultWhisperTemplate(false,'original user-compatible default')=='original user-compatible default')
ForeverQuickJoinDB.translateDungeonNames=nil
assert(not locale.DungeonNamesEnabled(),'English defaults dungeon translation to off')
locale.Select('frFR')
assert(locale.DungeonNamesEnabled(),'French defaults dungeon translation to on')
local main=assert(io.open('ForeverQuickJoin.lua','rb')):read('*a')
local chat=assert(io.open('ForeverQuickJoin_Chat.lua','rb')):read('*a')
local theme=assert(io.open('ForeverQuickJoin_Theme.lua','rb')):read('*a')
local listing=assert(io.open('ForeverQuickJoin_Listing.lua','rb')):read('*a')
assert(main:find('LocalizeDungeonActivityName',1,true))
assert(main:find('window.QuickJoinLanguageChanged = function()',1,true))
assert(theme:find('Translate Dungeon Names',1,true))
assert(theme:find('Theme / Language:',1,true))
assert(listing:find('ForeverQuickJoinLocale',1,true))
assert(chat:find('QuestChatText',1,true))
local toc=assert(io.open('ForeverQuickJoin.toc','rb')):read('*a')
assert(toc:find('ForeverQuickJoin_Locale.lua',1,true))
print('PASS localization: translated activity display, preferences, whisper defaults, UI integration')
