-- Build-time structural smoke test for the integrated LFG Chat module.
-- The in-game UI/event behavior is separately exercised by the mock runtime.
local function Read(path)
    local file=assert(io.open(path,"rb"),"Missing "..path)
    local contents=file:read("*a")
    file:close()
    return contents
end
local toc=Read("ForeverQuickJoin.toc")
local chat=Read("ForeverQuickJoin_Chat.lua")
local host=Read("ForeverQuickJoin_Host.lua")
local apps=Read("ForeverQuickJoin_Applications.lua")
local listing=Read("ForeverQuickJoin_Listing.lua")
local function Has(text,part)
    assert(text:find(part,1,true),"Missing expected code: "..part)
end
assert(toc:match("## Version: %d+%.%d+%.%d+"), "Missing semantic addon version")
Has(toc,"ForeverQuickJoin_Chat.lua")
Has(chat,'watcher:RegisterEvent("CHAT_MSG_CHANNEL")')
Has(chat,'watcher:RegisterEvent("CHAT_MSG_SAY")')
Has(chat,'watcher:RegisterEvent("CHAT_MSG_YELL")')
Has(chat,'JoinPermanentChannel,"LookingForGroup"')
Has(chat,'ForeverQuickJoinDB.chatAutoJoin')
Has(chat,'SetMode("listings")')
Has(chat,'Group Listings')
Has(chat,'LFG Chat')
Has(chat,'function HandleInviteFeedback')
Has(chat,'Chat messaging is locked')
Has(host,'if a.updatedAt ~= b.updatedAt then return a.updatedAt > b.updatedAt end')
Has(host,'inboxPage = 1 -- always surface a new incoming whisper at the top')
Has(apps,'entry.lastActivitySerial=nextActivitySerial')
Has(apps,'currentPage=1 -- ensure a new incoming reply is visible immediately')
Has(listing,'The redundant top-level Playstyle dropdown is intentionally retired.')
assert(not chat:find('debug.getupvalue',1,true) or chat:find('-- No debug.getupvalue',1,true),"Deprecated inbox introspection detected")
assert(not chat:find('ForeverQuickJoinChatPreviewDB',1,true),"Old test saved variable detected")
print("PASS chat release smoke: TOC, channel scanner, selection, invite feedback, recency, playstyle")
